import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

export type DataAsset = { url: string; sha256: string; bytes: number; layer: "core" | "description" };
export type DataManifest = { format: 2; dataVersion: string; schemaVersion: string; assets: Record<string, DataAsset> };
export const sha256 = (bytes: string | Uint8Array): string => createHash("sha256").update(bytes).digest("hex");

export function generatedDataset(manifest: DataManifest): string {
  return "// Generated by tools/src/build. A deployment pins one immutable dataset.\n" +
    `export const DATA_MANIFEST = ${JSON.stringify(`releases/${manifest.dataVersion}.json`)};\n` +
    `export const DATA_VERSION = ${JSON.stringify(manifest.dataVersion)};\n`;
}

export function publishDataRelease(dist: string, schemaVersion: string, logicalNames: Iterable<string>): DataManifest {
  const assets: Record<string, DataAsset> = {};
  for (const logical of [...new Set(logicalNames)].sort()) {
    const bytes = readFileSync(path.join(dist, logical));
    const digest = sha256(bytes);
    const url = `assets/data/${digest}${path.extname(logical)}`;
    assets[logical] = { url, sha256: digest, bytes: bytes.byteLength, layer: logical.startsWith("l2/") ? "description" : "core" };
    const assetPath = path.join(dist, url);
    mkdirSync(path.dirname(assetPath), { recursive: true });
    if (!existsSync(assetPath) || sha256(readFileSync(assetPath)) !== digest) writeFileSync(assetPath, bytes);
  }
  const digests = Object.entries(assets).map(([logical, asset]) => [logical, asset.sha256]);
  const dataVersion = sha256(JSON.stringify({ format: 2, schemaVersion, assets: digests }));
  const manifest: DataManifest = { format: 2, dataVersion, schemaVersion, assets };
  const manifestPath = path.join(dist, "releases", `${dataVersion}.json`);
  mkdirSync(path.dirname(manifestPath), { recursive: true });
  writeFileSync(manifestPath, JSON.stringify(manifest) + "\n");
  return manifest;
}

/** A cache hit is valid only while every pinned asset and source file is intact. */
export function completeDataRelease(dist: string, version: string | undefined, generatedPath: string): boolean {
  if (!version || !/^[0-9a-f]{64}$/.test(version)) return false;
  const releasePath = path.join(dist, "releases", `${version}.json`);
  if (!existsSync(releasePath) || !existsSync(generatedPath)) return false;
  try {
    const manifest: DataManifest = JSON.parse(readFileSync(releasePath, "utf8"));
    if (manifest.format !== 2 || manifest.dataVersion !== version || readFileSync(generatedPath, "utf8") !== generatedDataset(manifest)) return false;
    if (!manifest.assets["graph/adjacency.bin"] || !manifest.assets["search/routing.json"]) return false;
    for (const [logical, asset] of Object.entries(manifest.assets)) {
      for (const name of [logical, asset.url]) {
        const filePath = path.join(dist, name);
        if (!existsSync(filePath)) return false;
        const bytes = readFileSync(filePath);
        if (bytes.byteLength !== asset.bytes || sha256(bytes) !== asset.sha256) return false;
      }
    }
    const digests = Object.entries(manifest.assets).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0).map(([logical, asset]) => [logical, asset.sha256]);
    return sha256(JSON.stringify({ format: 2, schemaVersion: manifest.schemaVersion, assets: digests })) === version;
  } catch { return false; }
}
